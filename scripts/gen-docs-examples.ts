/**
 * Regenerates registry/main/examples/docs/index.ts from the example files on
 * disk. Run after adding docs examples: `bun scripts/gen-docs-examples.ts`.
 */
import { readdirSync, renameSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"

const base = "registry/main/examples/docs"
const files: string[] = []
for (const dir of readdirSync(base).sort()) {
  const full = path.join(base, dir)
  if (!statSync(full).isDirectory()) continue
  for (const f of readdirSync(full).sort()) if (f.endsWith(".tsx")) files.push(`${dir}/${f}`)
}
const ident = (name: string) => name.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("")
const lines = [
  "/* Generated by scripts/gen-docs-examples.ts — each entry renders live and shows its own source file. */",
  "",
  ...files.map((f) => `import ${ident(path.basename(f, ".tsx"))} from "@/${base}/${f.replace(/\.tsx$/, "")}"`),
  "",
  "export const examples = {",
  ...files.map((f) => `  "${path.basename(f, ".tsx")}": { component: ${ident(path.basename(f, ".tsx"))}, file: "${base}/${f}" },`),
  "} as const",
  "",
]
const out = path.join(base, "index.ts")
const tmp = `${out}.${process.pid}.tmp`
writeFileSync(tmp, lines.join("\n"))
// Atomic replace so concurrent runs never leave a half-written file.
renameSync(tmp, out)
console.log(`${files.length} docs examples indexed`)
